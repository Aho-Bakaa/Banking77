"""Phase 4b: Local evaluation scoring and benchmarking.

Takes the raw outputs generated by 04_generate_eval.py (from <eval_dir>/<set>__<mode>.jsonl)
and computes:
1. Top-1 Intent Accuracy & Top-3 Candidate Coverage on Banking77 test set (3,080 queries)
2. Ambiguity Detection Precision, Recall, F1 on synthetic ambiguity set (200 queries)
3. Train vs Test Gap (Memorisation check on 500 train queries)
4. Free Mode Routing Behavior (How often the model chooses <think> vs <fast> and accuracy per path)
5. Generation Latency & Token Efficiency across modes (free, fast, think)
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from collections import defaultdict
import numpy as np


def parse_model_output(raw_text: str) -> dict:
    """Extracts thinking trace and JSON payload from model output."""
    thought = None
    if "<think>" in raw_text:
        thought_part = raw_text.split("<think>", 1)[1]
        if "</think>" in thought_part:
            thought = thought_part.split("</think>", 1)[0].strip()
    
    # 1. Look for ```json ... ``` blocks
    json_match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", raw_text, re.DOTALL)
    if json_match:
        try:
            data = json.loads(json_match.group(1))
            data["_thought"] = thought
            data["_valid_json"] = True
            return data
        except Exception:
            pass

    # 2. Look for outermost balanced { ... }
    first_brace = raw_text.find("{")
    last_brace = raw_text.rfind("}")
    if first_brace != -1 and last_brace != -1 and last_brace > first_brace:
        try:
            data = json.loads(raw_text[first_brace:last_brace + 1])
            data["_thought"] = thought
            data["_valid_json"] = True
            return data
        except Exception:
            pass

    return {"status": "parse_error", "raw": raw_text, "_thought": thought, "_valid_json": False}


def load_records(path: Path) -> list[dict]:
    records = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                records.append(json.loads(line))
    return records


def evaluate_b77_test(records: list[dict]) -> dict:
    correct_top1 = 0
    correct_top3 = 0
    valid_json = 0
    chose_think = 0
    chose_fast = 0
    think_correct = 0
    think_total = 0
    fast_correct = 0
    fast_total = 0

    latencies = []
    token_counts = []

    for r in records:
        out = parse_model_output(r["output"])
        gold = r["gold"]
        latencies.append(r.get("seconds_per_query", 0))
        token_counts.append(r.get("n_new_tokens", 0))

        if out.get("_valid_json", False):
            valid_json += 1

        is_think = "<think>" in r["output"] or out.get("_thought") is not None
        if is_think:
            chose_think += 1
            think_total += 1
        else:
            chose_fast += 1
            fast_total += 1

        pred_intent = None
        if out.get("status") == "resolved":
            pred_intent = out.get("intent")
            is_match = (pred_intent == gold)
            if is_match:
                correct_top1 += 1
                correct_top3 += 1
                if is_think:
                    think_correct += 1
                else:
                    fast_correct += 1
        elif out.get("status") == "ambiguous":
            candidates = out.get("candidates", [])
            if candidates:
                pred_intent = candidates[0]
                if pred_intent == gold:
                    correct_top1 += 1
                    if is_think:
                        think_correct += 1
                    else:
                        fast_correct += 1
                if gold in candidates[:3]:
                    correct_top3 += 1

    n = len(records)
    return {
        "n_samples": n,
        "json_adherence": valid_json / max(n, 1),
        "top1_accuracy": correct_top1 / max(n, 1),
        "top3_accuracy": correct_top3 / max(n, 1),
        "think_pct": (chose_think / max(n, 1)) * 100,
        "think_accuracy": (think_correct / max(think_total, 1)) if think_total else 0.0,
        "fast_accuracy": (fast_correct / max(fast_total, 1)) if fast_total else 0.0,
        "mean_latency_ms": np.mean(latencies) * 1000 if latencies else 0.0,
        "p95_latency_ms": np.percentile(latencies, 95) * 1000 if latencies else 0.0,
        "mean_tokens": np.mean(token_counts) if token_counts else 0.0,
        "p95_tokens": np.percentile(token_counts, 95) if token_counts else 0.0,
    }


def evaluate_amb_test(records: list[dict]) -> dict:
    tp = 0  # correctly flagged ambiguous
    fn = 0  # falsely marked resolved
    jaccard_scores = []
    valid_json = 0

    for r in records:
        out = parse_model_output(r["output"])
        gold_cands = set(r.get("candidates_gold", []))
        if out.get("_valid_json", False):
            valid_json += 1

        status = out.get("status")
        if status == "ambiguous":
            tp += 1
            pred_cands = set(out.get("candidates", []))
            if gold_cands and pred_cands:
                jaccard = len(gold_cands & pred_cands) / len(gold_cands | pred_cands)
                jaccard_scores.append(jaccard)
            else:
                jaccard_scores.append(0.0)
        else:
            fn += 1

    n = len(records)
    recall = tp / max(n, 1)
    mean_jaccard = np.mean(jaccard_scores) if jaccard_scores else 0.0

    return {
        "n_samples": n,
        "json_adherence": valid_json / max(n, 1),
        "ambiguity_recall": recall,
        "mean_candidate_jaccard": mean_jaccard,
    }


def evaluate_b77_train500(records: list[dict]) -> dict:
    correct = 0
    for r in records:
        out = parse_model_output(r["output"])
        gold = r["gold"]
        if out.get("status") == "resolved" and out.get("intent") == gold:
            correct += 1
        elif out.get("status") == "ambiguous":
            candidates = out.get("candidates", [])
            if candidates and candidates[0] == gold:
                correct += 1

    n = len(records)
    return {"train_accuracy": correct / max(n, 1)}


def main() -> None:
    parser = argparse.ArgumentParser(description="Score Phase 4 evaluation outputs.")
    parser.add_argument("--eval-dir", required=True, type=Path, help="Directory containing eval JSONL files")
    parser.add_argument("--modes", nargs="+", default=["free", "fast", "think"])
    args = parser.parse_args()

    print("=" * 80)
    print(f"BANKING77 SLM EVALUATION REPORT — {args.eval_dir}")
    print("=" * 80)

    summary_rows = []

    for mode in args.modes:
        test_path = args.eval_dir / f"b77_test__{mode}.jsonl"
        amb_path = args.eval_dir / f"amb_test__{mode}.jsonl"
        train_path = args.eval_dir / f"b77_train500__{mode}.jsonl"

        if not test_path.exists():
            print(f"Skipping mode '{mode}': {test_path.name} not found.")
            continue

        test_recs = load_records(test_path)
        test_res = evaluate_b77_test(test_recs)

        amb_res = {}
        if amb_path.exists():
            amb_recs = load_records(amb_path)
            amb_res = evaluate_amb_test(amb_recs)

        train_res = {}
        if train_path.exists():
            train_recs = load_records(train_path)
            train_res = evaluate_b77_train500(train_recs)

        train_acc = train_res.get("train_accuracy", 0.0)
        test_acc = test_res.get("top1_accuracy", 0.0)
        gap = train_acc - test_acc

        summary_rows.append({
            "mode": mode,
            "top1_acc": test_acc * 100,
            "top3_acc": test_res.get("top3_accuracy", 0.0) * 100,
            "amb_recall": amb_res.get("ambiguity_recall", 0.0) * 100,
            "train_acc": train_acc * 100,
            "gap": gap * 100,
            "think_pct": test_res.get("think_pct", 0.0),
            "latency_ms": test_res.get("mean_latency_ms", 0.0),
            "tokens": test_res.get("mean_tokens", 0.0),
            "json_pct": test_res.get("json_adherence", 0.0) * 100,
        })

    # Print summary table
    print("\n" + "-" * 105)
    print(f"{'Mode':<8} | {'Top-1 Acc':<10} | {'Top-3 Acc':<10} | {'Amb Recall':<11} | {'Train500':<10} | {'Gap':<6} | {'Think %':<8} | {'Mean Latency':<13} | {'Avg Tokens':<10}")
    print("-" * 105)
    for row in summary_rows:
        print(
            f"{row['mode']:<8} | "
            f"{row['top1_acc']:>8.2f}% | "
            f"{row['top3_acc']:>8.2f}% | "
            f"{row['amb_recall']:>9.2f}% | "
            f"{row['train_acc']:>8.2f}% | "
            f"{row['gap']:>5.2f}% | "
            f"{row['think_pct']:>6.1f}% | "
            f"{row['latency_ms']:>9.1f} ms | "
            f"{row['tokens']:>8.1f}"
        )
    print("-" * 105)


if __name__ == "__main__":
    main()
